// Нормализация ответа
function normalizeAnswer(value) {
  return String(value)
    .toLowerCase()
    .trim()
    .replace(/\s+/g, "")
    .replace(/−/g, "-")
    .replace(/,/g, ";")
    .replace(/∞/g, "inf")
    .replace(/∪/g, "u")
    .replace(/√/g, "sqrt")
    .replace(/π/g, "pi")
    .replace(/²/g, "^2");
}

// Уникальный ID задания
function getTaskId(task) {
  const index = tasks.indexOf(task);
  return "task-" + index;
}

// Получить задания конкретного блока
function getTopicTasks(number) {
  return tasks
    .map((task, index) => ({ task, index }))
    .filter((item) => item.task.number === Number(number));
}

