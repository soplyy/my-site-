function nextTask() {
  const number = tasks[currentTask].number;
  const topicTasks = getTopicTasks(number);

  const position = topicTasks.findIndex((item) => item.index === currentTask);

  if (position < topicTasks.length - 1) {
    currentTask = topicTasks[position + 1].index;
    renderTask();
  } else {
    const nextTopic = [14, 15, 16, 17, 18, 19, 20].find(
      (n) => n > number && getTopicTasks(n).length > 0,
    );

    if (nextTopic !== undefined) {
      currentTask = getTopicTasks(nextTopic)[0].index;
      renderTask();
    }
  }
}

function previousTask() {
  const number = tasks[currentTask].number;
  const topicTasks = getTopicTasks(number);

  const position = topicTasks.findIndex((item) => item.index === currentTask);

  if (position > 0) {
    currentTask = topicTasks[position - 1].index;
    renderTask();
  } else {
    const previousTopics = [14, 15, 16, 17, 18, 19, 20].filter(
      (n) => n < number && getTopicTasks(n).length > 0,
    );

    if (previousTopics.length) {
      const previousNumber = previousTopics[previousTopics.length - 1];

      const previousTasks = getTopicTasks(previousNumber);

      currentTask = previousTasks[previousTasks.length - 1].index;
      renderTask();
    }
  }
}

