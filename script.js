// =========================================

function renderTask() {
  if (!tasks.length) {
    elements.taskCondition.textContent = "Задания пока не добавлены.";
    return;
  }

  const task = tasks[currentTask];
  const info = topicInfo[task.number];

  if (!task || !info) return;

  const topicTasks = getTopicTasks(task.number);
  const position = topicTasks.findIndex((item) => item.index === currentTask);

  elements.topicNumber.textContent = "ЗАДАНИЕ №" + task.number;
  elements.topicTitle.textContent = info.title;
  elements.topicDescription.textContent = info.description;

  elements.taskNumber.textContent = position + 1;
  elements.taskCategory.textContent = "МАТЕМАТИКА";
  elements.taskName.textContent = task.name;

  // ВАЖНО: правильный ID из твоего index.html
  elements.taskCondition.innerHTML = escapeHTML(task.description).replace(
    /\n/g,
    "<br>",
  );

  elements.answer.value = "";
  elements.result.innerHTML = "";

  elements.solution.innerHTML = "";
  elements.solution.classList.add("hidden");

  renderTopics();
  renderTaskNumbers();
  updateProgress();
}

// Защита текста задания от HTML-разметки
function escapeHTML(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

// =========================================
// ПРОВЕРКА ОТВЕТА
// =========================================

function checkAnswer() {
  const task = tasks[currentTask];

  const userAnswer = normalizeAnswer(elements.answer.value);

  if (!userAnswer) {
    elements.result.innerHTML =
      '<span style="color:#ffbd55">Сначала введи ответ.</span>';
    return;
  }

  const correct = task.answers.some((answer) => {
    return normalizeAnswer(answer) === userAnswer;
  });

  if (correct) {
    elements.result.innerHTML = `
            <div style="
                color:#42d99a;
                padding:12px;
                margin-top:10px;
                border-radius:8px;
                background:rgba(34,190,125,0.12);
            ">
                ✓ Правильно! Ответ совпал.
            </div>
        `;

    const id = getTaskId(task);

    if (!solved.includes(id)) {
      solved.push(id);

      localStorage.setItem("egeSolved2027", JSON.stringify(solved));
    }

    renderTopics();
    renderTaskNumbers();
    updateProgress();
  } else {
    elements.result.innerHTML = `
            <div style="
                color:#ff7777;
                padding:12px;
                margin-top:10px;
                border-radius:8px;
                background:rgba(255,70,70,0.12);
            ">
                ✗ Ответ неверный. Попробуй ещё раз
                или посмотри подробное решение.
            </div>
        `;
  }
}

